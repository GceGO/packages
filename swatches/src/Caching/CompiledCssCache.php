<?php

declare(strict_types=1);

namespace Gcego\Swatches\Caching;

/**
 * The compiled runtime CSS of registered themes and accents, as a PHP file (opcache friendly).
 *
 * Written by gcego:swatches:cache, removed by gcego:swatches:clear. Entries are used
 * only while the fingerprint of the registered themes still matches, so a stale
 * cache is ignored instead of serving old colors.
 */
final readonly class CompiledCssCache
{
    public const int Version = 1;

    public function __construct(public string $path) {}

    /**
     * @return array{fingerprint: string, themes: array<string, string>, accents: array<string, string>}|null
     */
    public function read(): ?array
    {
        if (! is_file($this->path)) {
            return null;
        }

        $data = require $this->path;

        if (! is_array($data) || ($data['version'] ?? null) !== self::Version || ! is_string($data['fingerprint'] ?? null) || ! is_array($data['themes'] ?? null) || ! is_array($data['accents'] ?? null)) {
            return null;
        }

        $strings = static fn (array $map): array => array_filter($map, static fn (mixed $css, mixed $name): bool => is_string($css) && is_string($name), ARRAY_FILTER_USE_BOTH);

        /** @var array<string, string> $themes */
        $themes = $strings($data['themes']);
        /** @var array<string, string> $accents */
        $accents = $strings($data['accents']);

        return ['fingerprint' => $data['fingerprint'], 'themes' => $themes, 'accents' => $accents];
    }

    /**
     * @param  array<string, string>  $themes
     * @param  array<string, string>  $accents
     */
    public function write(string $fingerprint, array $themes, array $accents): void
    {
        $directory = dirname($this->path);

        if (! is_dir($directory)) {
            mkdir($directory, 0755, true);
        }

        $temporary = $this->path.'.'.bin2hex(random_bytes(4)).'.tmp';
        $export = var_export(['version' => self::Version, 'fingerprint' => $fingerprint, 'themes' => $themes, 'accents' => $accents], true);

        file_put_contents($temporary, "<?php\n\n// Generated by php artisan gcego:swatches:cache. Do not edit.\n\nreturn ".$export.";\n");
        rename($temporary, $this->path);

        if (function_exists('opcache_invalidate')) {
            opcache_invalidate($this->path, true);
        }
    }

    public function clear(): bool
    {
        return ! is_file($this->path) || unlink($this->path);
    }

    public function exists(): bool
    {
        return is_file($this->path);
    }
}
